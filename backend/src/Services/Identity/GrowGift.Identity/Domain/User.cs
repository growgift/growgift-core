using GrowGift.SharedKernel.Domain;
using GrowGift.SharedKernel.Results;

namespace GrowGift.Identity.Domain;

public enum UserRole { Buyer = 0, Parent = 1, Child = 2, Admin = 3, Recipient = 4 }
public enum KycStatus { NotStarted = 0, Pending = 1, Approved = 2, Rejected = 3 }

/// <summary>
/// Platform identity. Passwords are Argon2id hashes; TOTP secrets are
/// encrypted at rest with the KMS data key. A child user is created by a
/// parent, carries role=Child, and is structurally read-only: no authorization
/// policy in any service grants the Child role a mutating scope.
/// </summary>
public sealed class User : AggregateRoot<Guid>
{
    private User() { }

    public string Email { get; private set; } = default!;
    public string PasswordHash { get; private set; } = default!;
    public UserRole Role { get; private set; }
    public KycStatus Kyc { get; private set; }
    public string? PersonaInquiryRef { get; private set; }
    public string? ViewTradeAccountRef { get; private set; }
    public string? TotpSecretEncrypted { get; private set; }
    public bool MfaEnabled { get; private set; }
    public int FailedLoginCount { get; private set; }
    public DateTimeOffset? LockedUntilUtc { get; private set; }
    public DateTimeOffset CreatedAtUtc { get; private set; }
    public string? EmailVerificationTokenHash { get; private set; }
    public DateTimeOffset? EmailVerifiedAtUtc { get; private set; }
    public bool EmailVerified => EmailVerifiedAtUtc is not null;

    /// <summary>
    /// Default shipping address for gift boxes bought by this account.
    /// Buyers need one on file before checkout; recipients/parents don't
    /// require it (nothing physical ships to them through this flow).
    /// </summary>
    public ShippingAddress? ShippingAddress { get; private set; }

    public static Result<User> Register(
        string email, string passwordHash, UserRole role, ShippingAddress? shippingAddress = null)
    {
        if (!email.Contains('@') || email.Length > 254)
            return Result.Failure<User>(Error.Validation("user.email", "A valid email is required."));

        var user = new User
        {
            Id = Guid.NewGuid(),
            Email = email.Trim().ToLowerInvariant(),
            PasswordHash = passwordHash,
            Role = role,
            Kyc = KycStatus.NotStarted,
            CreatedAtUtc = DateTimeOffset.UtcNow,
            ShippingAddress = shippingAddress
        };
        user.Raise(new Events.Registered(user.Id, user.Email, role.ToString()));
        return user;
    }

    /// <summary>
    /// A child's read-only login — deliberately reuses the exact same
    /// Email/PasswordHash columns and the exact same /auth/login endpoint
    /// as a normal account, rather than building a parallel PIN-specific
    /// login mechanism. The "email" is really a short login code (no '@',
    /// generated by the caller — see Family's Child.LoginCode) and the
    /// "password" is really a short PIN, but PasswordHasher.Verify doesn't
    /// care what the string represents, and login's existing lockout
    /// (RecordFailedLogin/IsLockedOut) applies identically — a real benefit
    /// given a short numeric PIN is inherently easier to brute-force than a
    /// full password, so that existing protection matters even more here.
    /// Skips Register's '@' requirement since a login code isn't an email.
    /// </summary>
    public static Result<User> RegisterChildLogin(string loginCode, string pinHash)
    {
        if (string.IsNullOrWhiteSpace(loginCode) || loginCode.Length > 254)
            return Result.Failure<User>(Error.Validation("user.login_code", "A login code is required."));

        var user = new User
        {
            Id = Guid.NewGuid(),
            Email = loginCode.Trim().ToLowerInvariant(),
            PasswordHash = pinHash,
            Role = UserRole.Child,
            Kyc = KycStatus.NotStarted,
            CreatedAtUtc = DateTimeOffset.UtcNow
        };
        user.Raise(new Events.Registered(user.Id, user.Email, user.Role.ToString()));
        return user;
    }

    public Result SetShippingAddress(ShippingAddress address)
    {
        ShippingAddress = address;
        return Result.Success();
    }

    public bool IsLockedOut(DateTimeOffset now) => LockedUntilUtc is { } until && until > now;

    /// <summary>Stores only the SHA-256 hash of the emailed verification token.</summary>
    public void SetEmailVerificationToken(string tokenHashHex) =>
        EmailVerificationTokenHash = tokenHashHex;

    public Result VerifyEmail(string tokenHashHex)
    {
        if (EmailVerified) return Result.Success();
        if (EmailVerificationTokenHash is null ||
            !string.Equals(EmailVerificationTokenHash, tokenHashHex, StringComparison.OrdinalIgnoreCase))
            return Result.Failure(Error.Validation("email.invalid_token", "This verification link is invalid or has already been used."));

        EmailVerifiedAtUtc = DateTimeOffset.UtcNow;
        EmailVerificationTokenHash = null;
        return Result.Success();
    }

    public void RecordFailedLogin(DateTimeOffset now)
    {
        FailedLoginCount++;
        if (FailedLoginCount >= 5)
            LockedUntilUtc = now.AddMinutes(Math.Min(60, Math.Pow(2, FailedLoginCount - 5) * 5));
    }

    public void RecordSuccessfulLogin()
    {
        FailedLoginCount = 0;
        LockedUntilUtc = null;
    }

    public void EnableMfa(string encryptedTotpSecret)
    {
        TotpSecretEncrypted = encryptedTotpSecret;
        MfaEnabled = true;
    }

    public void StartKyc(string personaInquiryRef)
    {
        PersonaInquiryRef = personaInquiryRef;
        Kyc = KycStatus.Pending;
    }

    public Result CompleteKyc(string outcome, string? viewTradeAccountRef)
    {
        if (Kyc != KycStatus.Pending)
            return Result.Failure(Error.Conflict("kyc.state", "No KYC inquiry is pending."));

        Kyc = outcome == "approved" ? KycStatus.Approved : KycStatus.Rejected;
        ViewTradeAccountRef = viewTradeAccountRef;
        Raise(new Events.KycCompleted(Id, PersonaInquiryRef!, outcome));
        return Result.Success();
    }

    /// <summary>Prefix of the fake account number the Development-only "simulate KYC" shortcut hands out.</summary>
    public const string SimulatedAccountPrefix = "VT-DEV-";

    public static bool IsSimulatedAccount(string? accountRef) =>
        accountRef is not null && accountRef.StartsWith(SimulatedAccountPrefix, StringComparison.Ordinal);

    /// <summary>
    /// A user who "verified" with the dev shortcut holds a fake account that doesn't exist at ViewTrade.
    /// When a REAL account is later linked or opened for them, swap it in. Only ever replaces a simulated
    /// account, only with a non-simulated one, and only while KYC is already Approved — a real account is
    /// never overwritten.
    /// </summary>
    public Result ReplaceSimulatedAccount(string realAccountRef)
    {
        if (Kyc != KycStatus.Approved || !IsSimulatedAccount(ViewTradeAccountRef))
            return Result.Failure(Error.Conflict("kyc.state", "Account isn't a simulated one."));
        if (string.IsNullOrWhiteSpace(realAccountRef) || IsSimulatedAccount(realAccountRef))
            return Result.Failure(Error.Validation("kyc.account", "Replacement must be a real account reference."));
        ViewTradeAccountRef = realAccountRef;
        return Result.Success();
    }

    /// <summary>
    /// Used when linking an existing account as a family partner/co-parent
    /// (see Family's Partner.cs) — their next login token needs role=parent
    /// so the existing "Parent" authorization policy (RequireClaim("role",
    /// "parent")) recognizes them without that policy needing to know
    /// anything about family/partner relationships itself. A no-op if
    /// they're already a parent (e.g. linking two parent accounts together).
    /// </summary>
    public void PromoteToParent()
    {
        if (Role != UserRole.Parent) Role = UserRole.Parent;
    }

    public static class Events
    {
        public sealed record Registered(Guid UserId, string Email, string Role) : DomainEvent;
        public sealed record KycCompleted(Guid UserId, string PersonaInquiryRef, string Outcome) : DomainEvent;
    }
}
